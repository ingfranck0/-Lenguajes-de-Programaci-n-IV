    private void btncalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalcularActionPerformed
try {
        // Obtener los valores de las cajas de texto
        double peso = Double.parseDouble(txtpeso.getText());
        double altura = Double.parseDouble(txtestatura.getText());

        // Validar los datos
        if (peso <= 0 || altura <= 0) {
            JOptionPane.showMessageDialog(this,
                    "El peso y la estatura deben ser mayores que cero");
            return;
        }

        // Calcular el IMC
        double IMC = peso / (altura * altura);

        // Mostrar el resultado
        JOptionPane.showMessageDialog(this,
                String.format("Su IMC es: %.2f", IMC));

        // Determinar el peso
        if (IMC < 18.5) {
            JOptionPane.showMessageDialog(this, "Bajo peso");

        } else if (IMC < 25) {
            JOptionPane.showMessageDialog(this, "Peso NORMAL");

        } else if (IMC < 30) {
            JOptionPane.showMessageDialog(this, "Sobrepeso");

        } else {
            JOptionPane.showMessageDialog(this, "Obesidad");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Por favor, introduce números válidos.");
    }
    }//GEN-LAST:event_btncalcularActionPerformed

